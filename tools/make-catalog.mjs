// Rebuilds netlify/lib/catalog.mjs from public/index.html so the server
// charges exactly the prices and sizes the site shows. Run after any
// change to prints, sizes or prices:  node tools/make-catalog.mjs
import { readFileSync, writeFileSync } from "node:fs";
const html = readFileSync(new URL("../public/index.html", import.meta.url), "utf8");
const start = html.indexOf("const RAW");
const end = html.indexOf("const $ =");
if (start < 0 || end < 0) throw new Error("Catalog section not found in index.html");
const code = html.slice(start, end) +
  "\nreturn { PRINTS, PRICES, MATERIALS, ALL_SIZES, sizesFor };";
const { PRINTS, PRICES, MATERIALS, ALL_SIZES, sizesFor } = new Function(code)();
const prints = {};
for (const p of PRINTS) {
  prints[p.id] = { title: p.title, master: p.master, sizes: sizesFor(p).map((s) => s.id) };
}
const out = `// GENERATED by tools/make-catalog.mjs from public/index.html. Do not edit by hand.
export const PRINTS = ${JSON.stringify(prints).replace(/},"/g, "},\n \"")};
export const PRICES = ${JSON.stringify(PRICES)};
export const MATERIALS = ${JSON.stringify(Object.fromEntries(MATERIALS.map((m) => [m.id, m.label])))};
export const SIZE_LABELS = ${JSON.stringify(Object.fromEntries(ALL_SIZES.map((s) => [s.id, s.label])))};
`;
writeFileSync(new URL("../netlify/lib/catalog.mjs", import.meta.url), out);
console.log("catalog:", Object.keys(prints).length, "prints");
